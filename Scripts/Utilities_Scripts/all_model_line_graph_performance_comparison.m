%% Comparative Performance Line Graph
% Data source: Updated Table 11
% Test set: 489 images

clear;
clc;
close all;

%% Performance metrics
metrics = categorical({'Accuracy', ...
                        'Macro-Precision', ...
                        'Macro-Recall', ...
                        'Macro-F1', ...
                        'Weighted-F1'});

metrics = reordercats(metrics, ...
    {'Accuracy','Macro-Precision','Macro-Recall', ...
     'Macro-F1','Weighted-F1'});

%% Table 11 values (%)

EfficientNet_B0 = [57.87 57.57 59.07 57.84 57.48];

Channel_Attention = [93.46 94.07 94.11 94.02 93.39];

Spatial_Attention = [95.50 95.76 95.42 95.58 95.51];

CBAM = [81.39 84.78 80.49 82.01 81.77];

Adaptive_Attention = [97.14 97.32 97.34 97.32 97.13];

%% Create figure
figure('Units','pixels', ...
       'Position',[100 100 1100 650], ...
       'Color','w');

hold on;

%% Plot comparative lines

plot(metrics, EfficientNet_B0, '-o', ...
    'LineWidth',2, 'MarkerSize',8);

plot(metrics, Channel_Attention, '-s', ...
    'LineWidth',2, 'MarkerSize',8);

plot(metrics, Spatial_Attention, '-^', ...
    'LineWidth',2, 'MarkerSize',8);

plot(metrics, CBAM, '-d', ...
    'LineWidth',2, 'MarkerSize',8);

plot(metrics, Adaptive_Attention, '-p', ...
    'LineWidth',2.8, 'MarkerSize',11, ...
    'Color',[0.85 0.10 0.10], ...
    'MarkerFaceColor',[0.85 0.10 0.10]);

%% Axis formatting

ylim([50 100]);
yticks(50:5:100);

ylabel('Performance (%)', ...
    'FontSize',16, 'FontWeight','bold');

xlabel('Evaluation Metrics', ...
    'FontSize',16, 'FontWeight','bold');

title('Comparative Performance of EfficientNet-Based Models', ...
    'FontSize',18, 'FontWeight','bold');

%% Legend

legend({'EfficientNet-B0', ...
        'Channel Attention', ...
        'Spatial Attention', ...
        'CBAM', ...
        'Adaptive Attention'}, ...
        'Location','southoutside', ...
        'Orientation','horizontal', ...
        'FontSize',12);

%% Grid and formatting

grid on;
box on;

set(gca, ...
    'FontSize',13, ...
    'FontWeight','bold', ...
    'LineWidth',1.2, ...
    'GridAlpha',0.20);

xtickangle(0);

%% Export publication-quality figures

exportgraphics(gcf, ...
    'Figure_Table11_Comparative_Performance.png', ...
    'Resolution',600);

exportgraphics(gcf, ...
    'Figure_Table11_Comparative_Performance.pdf', ...
    'ContentType','vector');

hold off;

disp('Comparative graph generated successfully.');